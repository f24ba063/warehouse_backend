    MAIL VARCHAR2(100),						--
    IS_VISIBLE INT NOT NULL DEFAULT 1		--
);

-- =========================
-- 6. LOCATION_MASTER(棚所在特定)
-- =========================
CREATE TABLE LOCATION_MASTER (
    WAREHOUSE_ID BIGINT NOT NULL,		--倉庫ID
    ZONE_ID CHAR(3) NOT NULL,			--区域ID
    SHELF_ID CHAR(5) NOT NULL,			--棚ID
    RACK_ID CHAR(3) NOT NULL,			--ラックID
    LOCATION_ID VARCHAR2(30),			--区域、棚、ラックをまとめたID
    PLACING_SIZE VARCHAR2(50),			--ラックの大きさ
    CATEGORY VARCHAR2(30),				--対応する商品カテゴリ
    MAX_CAPACITY NUMBER(16,4),			--商品のUNIT_OF_MEASUREに対応する、
    IS_VISIBLE NUMBER(1) NOT NULL DEFAULT 1,--可視フラグ
    CONSTRAINT PK_LOCATION_MASTER
    PRIMARY KEY (WAREHOUSE_ID, ZONE_ID, RACK_ID, SHELF_ID),
    CONSTRAINT UK_LOCATION_ID
    UNIQUE (LOCATION_ID),
    CONSTRAINT FK_LOCATION_WAREHOUSE
    FOREIGN KEY (WAREHOUSE_ID) REFERENCES WAREHOUSE_MASTER(WAREHOUSE_ID)
);

-- =========================
-- 7. INCOMING_HEAD(荷物受入ヘッダー)
-- =========================
CREATE TABLE INCOMING_HEAD (
    INCOMING_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SUPPLIER_ID NUMBER,	 		--発送者
    WAREHOUSE_ID NUMBER, 		--格納先倉庫
    SHIPMENT_NO VARCHAR(20),	--発送便番号
    DOCUMENT_NO VARCHAR(20),	--相手側の伝票番号
    ORDER_DATE DATE, 			--発注日
    ORDER_STATUS VARCHAR(10), 	--発注品の発送状態
    ORDER_PRIORITY INT, 		--緊急度、優先度
    RECEIVE_STATUS VARCHAR(10), --受入倉庫側のステータス（検品中、受入完了など）
    DELIVERY_DATE DATE, 		--納期予定日
    RECEIVED_DATE DATE, 		--納品実績
    CREATED_BY BIGINT, 			--伝票作成者
    CREATED_AT TIMESTAMP, 		--伝票作成日時
    UPDATED_BY BIGINT, 			--発送状態管理者
    UPDATED_AT TIMESTAMP, 		--発送状態最終変更日時
    REMARK VARCHAR(200), 		--特記事項
    FOREIGN KEY (SUPPLIER_ID) REFERENCES PARTNER_MASTER(PARTNER_ID)
);

-- =========================
-- 8. INCOMING_DETAIL(荷物受入詳細)
-- =========================
CREATE TABLE INCOMING_DETAIL (
    INCOMING_ID BIGINT NOT NULL,	--ヘッダーID
    LINE_NO INT NOT NULL,			--伝票上の並び順
    PRODUCT_ID BIGINT,				--商品ID
    UNIT VARCHAR2(20),				--受入単位（箱、パレットなど）
    INPUT_QTY INT, 					--入力発注数
    CALCULATED_QTY INT,				--入力発注数を最小単位で換算した数値
    RECEIVED_QTY INT,				--実受領数
    STORAGE_LOCATION VARCHAR2(30),	--倉庫内のどの棚に配置か
    EXPIRE_DATE DATE, 				--消費期限（食品、医療品など）
    ITEM_WEIGHT NUMBER(16,4),		--受入商品の総重量
    VOLUME VARCHAR2(30), 			--商品の大きさ
    QUALITY_STATUS VARCHAR(5),		--品質判定（合格、要確認、不合格など）
    LOT_NO VARCHAR2(100),			--ロット番号
    REMARK VARCHAR2(100),			--特記事項
    PRIMARY KEY (INCOMING_ID, LINE_NO),
    FOREIGN KEY (INCOMING_ID) REFERENCES INCOMING_HEAD(INCOMING_ID),
    FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT_MASTER(PRODUCT_ID)
);

-- =========================
-- 9. OUTGOING_HEAD(荷物発送ヘッダー)
-- =========================
CREATE TABLE OUTGOING_HEAD (
    OUTGOING_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SHIPPER_WAREHOUSE_ID NUMBER,--発送元倉庫ID
    DESTINATION_ID NUMBER, 		--発送先拠点ID
    SHIPMENT_NO VARCHAR2(20),	--出荷便番号(自社側)
    DOCUMENT_NO VARCHAR2(20),	--伝票番号(受入側)
    ORDER_DATE DATE,			--受注日
    ORDER_PRIORITY INT, 		--優先度
    ESTIMATED_DATE DATE, 		--出庫予定日
    SHIPPED_DATE DATE, 			--出庫実績
    CREATED_BY BIGINT, 			--伝票作成者
    CREATED_AT TIMESTAMP, 		--伝票作成日時
    UPDATED_BY BIGINT, 			--発送状態管理者
    UPDATED_AT TIMESTAMP, 		--発送状態最終変更日時
    REMARK VARCHAR(200) 		--特記事項
);


-- =========================
-- 10. OUTGOING_DETAIL(荷物発送詳細)
-- =========================
CREATE TABLE OUTGOING_DETAIL (
    OUTGOING_ID BIGINT NOT NULL,	--発送伝票ID
    LINE_NO INT NOT NULL,			--伝票上の並び順

    PRODUCT_ID BIGINT NOT NULL,		--商品ID
    SHIPPING_QUANTITY INT NOT NULL,	--発送量

    FROM_LOCATION_ID VARCHAR2(30),   --どの棚から出したか
    LOT_NO VARCHAR(100),			--ロット番号

    PICKING_STATUS VARCHAR2(10),      -- 未処理/ピッキング済
    REMARK VARCHAR2(100),

    PRIMARY KEY (OUTGOING_ID, LINE_NO)
);

-- =========================
-- 11. LOT_MASTER(ロット管理マスター)
-- =========================
CREATE TABLE LOT_MASTER (
    PRODUCT_ID BIGINT NOT NULL,			--商品ID
    LOT_NO VARCHAR2(30) NOT NULL,			--ロット番号
    CREATION_DATE TIMESTAMP NOT NULL,	--製造日
    SUPPLIER_ID NUMBER,					--搬送
    FACTORY_ID NUMBER,					--製造工場
    EXPIRATION_DATE DATE,				--消費期限
    QC_STATUS_ID CHAR(1) NOT NULL,		--製品状態
	RECEIVED_DATE DATE,					--搬入日
	REMARK VARCHAR2(200),				--特記事項
	CREATED_BY BIGINT,					--レコード作成者
    CREATED_AT TIMESTAMP,				--レコード作成日時
    UPDATED_BY BIGINT,					--レコード最終更新者
    UPDATED_AT TIMESTAMP,				--レコード最終更新日
	IS_VISIBLE INT NOT NULL DEFAULT 1,	--可視フラグ
    PRIMARY KEY (PRODUCT_ID, LOT_NO),
    FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT_MASTER(PRODUCT_ID),
    FOREIGN KEY (SUPPLIER_ID) REFERENCES PARTNER_MASTER(PARTNER_ID)
);

-- =========================
-- xx. LOT_COST(ロットごとの単価計算・円換算後のみ受入)
--価格管理については一切かかわらない設計なので、これは使わない
-- =========================
CREATE TABLE LOT_COST (
    PRODUCT_ID BIGINT NOT NULL,
    LOT_NO VARCHAR2(20) NOT NULL,
    CONVERTED_COST_JPY DECIMAL(14,2) NOT NULL,
    PRIMARY KEY (PRODUCT_ID, LOT_NO),
    FOREIGN KEY (PRODUCT_ID, LOT_NO) REFERENCES LOT_MASTER(PRODUCT_ID, LOT_NO)  
);

-- =========================
-- 12. INVENTORY_STOCK(商品所在管理)
-- =========================
CREATE TABLE INVENTORY_STOCK (
    STOCK_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PRODUCT_ID BIGINT,
    WAREHOUSE_ID BIGINT,
    LOCATION_ID VARCHAR2(30),
    LOT_NO VARCHAR2(30),
    STOCK INT NOT NULL,
    UNIQUE (PRODUCT_ID, LOCATION_ID, LOT_NO),
    FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT_MASTER(PRODUCT_ID)
);

