CREATE TABLE LOCATION_MASTER (
	WAREHOUSE_ID BIGINT NOT NULL,		--倉庫ID
	ZONE_ID CHAR(3) NOT NULL,			--区域ID
	SHELF_ID CHAR(5) NOT NULL,			--棚ID
	RACK_ID CHAR(3) NOT NULL,			--ラックID
