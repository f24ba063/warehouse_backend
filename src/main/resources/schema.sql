CREATE TABLE WAREHOUSE_MASTER (
    WAREHOUSE_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    WAREHOUSE_NAME VARCHAR2(50) NOT NULL,	--
    WAREHOUSE_ADDRESS_1 VARCHAR2(100),		--
    WAREHOUSE_ADDRESS_2 VARCHAR2(100),		--
    WAREHOUSE_ADDRESS_3 VARCHAR2(100),		--
