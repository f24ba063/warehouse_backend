-- 12. USER_COLUMN(ユーザー)
-- =========================
CREATE TABLE USER_COLUMN (
	USER_ID BIGINT NOT NULL,
	COLUMN_KEY VARCHAR2(30) NOT NULL,
	IS_VISIBLE NUMBER(1) DEFAULT 1 CHECK (IS_VISIBLE IN (0,1)),--閲覧可能なら1、不可能ならO
	IS_ACTIVE NUMBER(1) DEFAULT 1 CHECK (IS_ACTIVE IN (0,1)),--閲覧制御機能が動いていたら1、止まっていたら0
	PRIMARY KEY(USER_ID, COLUMN_KEY),
	FOREIGN KEY(USER_ID) REFERENCES APP_USER(USER_ID)
);

-- =========================
-- 13. EXTENSION_COLUMN
-- =========================
CREATE TABLE EXTENSION_COLUMN(
	EXTENSION_ITEM_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	COLUMN_KEY VARCHAR2(30) UNIQUE,--USER_COLUMNテーブルの列名キー
	DISPLAY_NAME VARCHAR2(30),	--画面に表示される列名
	DATA_TYPE VARCHAR2(16),		--データ型（STRING、NUMBERなど）
	IS_REQUIRED NUMBER DEFAULT 0 CHECK (IS_REQUIRED IN(1,0)),	--必須かどうかの制御。1だと必須、0だと自由
	APPLY_TARGET VARCHAR2(10) DEFAULT 'ALL',	--表示設定の対象範囲。「ALL」、「INCOMING」、「OUTGOING」、「STOCK」で機能先が変わる
	IS_ACTIVE NUMBER DEFAULT 1 CHECK (IS_ACTIVE IN(1,0))	--機能が生きているかどうかのフラグ
);
-- =========================
