);

-- =========================
-- 7. INCOMING_ORDER_DETAIL(発注詳細)(本社社員が発行する)
-- =========================

CREATE TABLE INCOMING_ORDER_DETAIL(
	INCOMING_ORDER_ID BIGINT,
	LINE_NO INT NOT NULL,			--伝票上の並び順
    PRODUCT_ID BIGINT NOT NULL,		--商品ID
    FACTORY_ID BIGINT NOT NULL,		--製造工場ID
    UNIT VARCHAR2(20),				--受入単位（箱、パレットなど）
    INPUT_QTY INT, 					--入力発注数(パッケージ数え)
    CALCULATED_QTY INT,				--入力発注数を最小単位で換算した数値
    EXPIRE_DATE DATE, 				--消費期限（食品、医療品など）
    QUALITY_STATUS VARCHAR2(5),		--品質判定（合格、要確認、不合格など）
    REMARK VARCHAR2(100),			--特記事項
    PRIMARY KEY (INCOMING_ORDER_ID, LINE_NO),
    FOREIGN KEY (INCOMING_ORDER_ID) REFERENCES INCOMING_ORDER_HEADER(INCOMING_ORDER_ID),
    FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT_MASTER(PRODUCT_ID)
);

-- =========================
-- 7. INCOMING_HEAD(入庫ヘッダー)
-- =========================
CREATE TABLE INCOMING_HEADER (
    INCOMING_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    VENDOR_ID NUMBER,	 		--発送者
    WAREHOUSE_ID NUMBER, 		--搬入先倉庫
    SHIPMENT_NO VARCHAR(20),	--発送便番号
    DOCUMENT_NO VARCHAR(20),	--相手側の伝票番号
    ORDER_DATE DATE, 			--発注日
    ORDER_STATUS VARCHAR(10), 	--発注品の発送状態
    ORDER_PRIORITY INT, 		--緊急度、優先度
    RECEIVE_STATUS VARCHAR(10), --受入倉庫側のステータス（検品中、受入完了、保留、返品など）
    DELIVERY_DATE DATE, 		--納期予定日
    RECEIVED_DATE DATE, 		--納品実績
    CREATED_BY BIGINT, 			--伝票作成者
    CREATED_AT TIMESTAMP, 		--伝票作成日時
    UPDATED_BY BIGINT, 			--発送状態管理者
    UPDATED_AT TIMESTAMP, 		--発送状態最終変更日時
    REMARK VARCHAR(200), 		--特記事項
    FOREIGN KEY (VENDOR_ID) REFERENCES VENDOR_MASTER(VENDOR_ID)
);


