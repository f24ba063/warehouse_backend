-- 7. INCOMING_ORDER_HEAD(発注ヘッダー)(本社社員が発行する)
-- =========================
CREATE TABLE INCOMING_ORDER_HEADER(
	INCOMING_ORDER_ID BIGINT PRIMARY KEY,
	ORDERER BIGINT,					--発注者
	ORDER_DATETIME TIMESTAMP,		--オーダー発生日時
	DESTINATION_WAREHOUSE BIGINT,	--送り先倉庫
	ESTIMATED_DATE DATE,			--到着予定日
