-- 5. PRODUCT_MASTER
-- =========================
CREATE TABLE PRODUCT_MASTER (
	PRODUCT_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	PRODUCT_NAME VARCHAR2(255) NOT NULL,			--商品名
	MAKER_NAME VARCHAR2(100) NOT NULL,				--製造メーカー名
	CATEGORY VARCHAR2(30),							--商品カテゴリ
	UNIT_OF_MEASURE VARCHAR2(10) NOT NULL,			--取扱い単位(枚、kgなどの意味)
	SAFETY_STOCK INT,								--安全在庫数
	ORDER_QTY INT NOT NULL,							--発注単位数
	MIN_ORDER_QTY INT,								--最小発注単位数
	PACKAGE_QTY INT,								--箱（ケース）あたりの個数
	PALLET_QTY INT,									--パレットあたりの箱数
	IS_LOT_MANAGED NUMBER(1) NOT NULL,				--ロット管理フラグ
	IS_ACTIVE NUMBER(1) DEFAULT 0,					--販売開始フラグ
	IS_VISIBLE NUMBER(1) DEFAULT 1 NOT NULL,		--可視（削除）フラグ
	CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,	--記事作成日時
	CREATED_BY BIGINT,								--記事作成者
	LAST_UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,--記事最終更新日時
	LAST_UPDATED_BY BIGINT,							--記事最終更新者
	CONSTRAINT FK_PRODUCT_MAKER FOREIGN KEY (MAKER_NAME)
	REFERENCES MAKER_MASTER(MAKER_NAME)
);

